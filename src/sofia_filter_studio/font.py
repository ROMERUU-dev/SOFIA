def _plain(text: str) -> str:
    """Upper case without accents; characters the font lacks become spaces."""
    text = unicodedata.normalize("NFKD", text.replace("µ", "u").replace("·", "-")).encode("ascii", "ignore").decode()
    return "".join(char if char in GLYPHS else " " for char in text.upper())


def text_width(text: str, height: float) -> float:
    return len(_plain(text)) * height * 5 / 6 - height / 6


def text_strokes(text: str, x: float, y: float, height: float, anchor: str = "start") -> list[list[tuple[float, float]]]:
    """Polylines (mm, y down) for ``text`` with its top-left at (x, y); anchor middle centers it."""
    unit = height / 6
    if anchor == "middle":
        x -= text_width(text, height) / 2
    strokes = []
    for index, char in enumerate(_plain(text)):
        left = x + index * 5 * unit
        for line in GLYPHS[char]:
            strokes.append([(left + px * unit, y + py * unit) for px, py in line])
    return strokes
